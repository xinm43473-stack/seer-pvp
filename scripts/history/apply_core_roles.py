def build_classes(sid: int, roles: list[str]) -> list[str]:
    if sid in CLASS_OVERRIDE:
        return list(CLASS_OVERRIDE[sid])
    out = []
    for r in roles:
        c = CLASS_LEGACY.get(r, "特殊")
        if c not in out:
            out.append(c)
    return out[:2] or ["特殊"]

