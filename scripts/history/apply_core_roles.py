def main() -> int:
    # 前端导出的编辑补丁（scripts/apply_view_edits.py 写入）优先于默认 ASSIGN。
    # 这样编辑结果可复现、且重跑本脚本不会被覆盖。
    edits_path = ROOT / "references" / "view_edits.json"
    view_edits: dict[int, dict] = {}
    if edits_path.exists():
        for item in json.loads(edits_path.read_text(encoding="utf-8")).get("edits", []):
            sid = item.get("id")
            if sid is None:
                continue
            sid = int(sid)
            if sid not in ASSIGN:
                continue
            if item.get("roles"):
                ASSIGN[sid] = list(item["roles"])
            if item.get("classes"):
                CLASS_OVERRIDE[sid] = list(item["classes"])
            view_edits[sid] = item
    doc = json.loads(ROSTER.read_text(encoding="utf-8"))
    spirits = doc["spirits"]
    ids = {x["id"] for x in spirits}
    missing = sorted(ids - set(ASSIGN))
    extra = sorted(set(ASSIGN) - ids)
    bad = [(sid, v) for sid, v in ASSIGN.items()
           if not (1 <= len(v) <= 3) or any(r not in CORE_ROLES for r in v)
           or len(set(v)) != len(v)]
    if missing or extra or bad:
        print("ASSIGN 不完整或非法：", missing, extra, bad)
        return 1

    legacy = {}
    for sp in spirits:
        sid = sp["id"]
        old = list(sp.get("roles", []))
        if "legacy_roles" not in sp:
            legacy[sid] = old
            sp["legacy_roles"] = old
        else:
            legacy[sid] = sp["legacy_roles"]
        sp["roles"] = list(ASSIGN[sid])
        sp["classes"] = build_classes(sid, ASSIGN[sid])
        note = (view_edits.get(sid) or {}).get("editor_note", "")
        if note:
            sp["editor_note"] = note
        else:
            sp.pop("editor_note", None)

    out = {
        "schema_version": 2.0,
        "generated_at": "2026-11-06",
        "purpose": "核心定位唯一口径源：一级 6 大类（配队骨架，可多标签）＋二级特色机制位（最突出、最能与同类区分的结算特色）；宽泛到什么精灵都能填的功能位不算定位。",
        "rule": [
            "每只深研精灵只写 1-2 个最突出、最能与同类区分的特色机制位，宁少勿滥；机制碎片、体系名、BP 池归属、月榜标签一律不作定位。",
            "定位必须来自 core_roles 词表；2026-11-06 用户纠正：如果什么精灵都能填、还不是很突出，就等于没有定位。",
            "相似定位组只由「共享同一个可辨识结算机制」的 2-3 只构成，禁止按泛功能位或能力清单凑组。",
            "同一只精灵最多属于一个相似定位组，且该组必须匹配其第 1 个特色定位；没有同类就不建组，直接写「暂无已核实关联」。",
            "2026-11-06 用户补充：一级定位先按 6 大类（主力／突破手／拦截／辅助／干扰／特殊）分，允许一只精灵有 1-3 个类标签（部分精灵多定位）；二级特色机制位保持不变。",
        ],
        "core_roles": CORE_ROLES,
        "role_classes": ROLE_CLASSES,
        "spirit_classes": {str(k): build_classes(k, v) for k, v in sorted(ASSIGN.items())},
        "spirits": {str(k): v for k, v in sorted(ASSIGN.items())},
        "legacy_roles": {str(k): v for k, v in sorted(legacy.items())},
        "stats": {
            "spirits": len(spirits),
            "core_roles": len(CORE_ROLES),
            "legacy_distinct": len({r for v in legacy.values() for r in v}),
            "per_spirit": {str(n): sum(1 for v in ASSIGN.values() if len(v) == n)
                           for n in (1, 2, 3)},
            "role_classes": len(ROLE_CLASSES),
            "classes_per_spirit": {str(n): sum(1 for k in ASSIGN if len(build_classes(k, ASSIGN[k])) == n)
                                   for n in (1, 2, 3)},
        },
    }
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    ROSTER.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("core roles: %d spirits / %d terms / legacy %d distinct words" %
          (out["stats"]["spirits"], out["stats"]["core_roles"], out["stats"]["legacy_distinct"]))
    print("per spirit:", out["stats"]["per_spirit"])
    return 0


